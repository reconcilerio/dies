package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestReadHeader(t *testing.T) {
	for name, tc := range map[string]struct {
		src, want, err string
	}{
		"a block comment": {src: "/*\nCopyright Example.\n*/\n", want: "/*\nCopyright Example.\n*/\n\n"},
		"line comments":   {src: "// Copyright Example.\n// SPDX-License-Identifier: MIT\n", want: "// Copyright Example.\n// SPDX-License-Identifier: MIT\n\n"},
		"nothing":         {src: "\n\n", want: ""},
		"code":            {src: "// Copyright Example.\npackage x\n", err: "only comments, found package"},
		"an open comment": {src: "/* Copyright Example.\n", err: "comment not terminated"},
	} {
		t.Run(name, func(t *testing.T) {
			file := filepath.Join(t.TempDir(), "boilerplate.go.txt")
			if err := os.WriteFile(file, []byte(tc.src), 0o644); err != nil {
				t.Fatal(err)
			}
			got, err := readHeader(file)
			switch {
			case tc.err != "" && (err == nil || !strings.Contains(err.Error(), tc.err)):
				t.Errorf("error %v, want %q", err, tc.err)
			case tc.err == "" && err != nil:
				t.Errorf("unexpected error: %v", err)
			case got != tc.want:
				t.Errorf("header %q, want %q", got, tc.want)
			}
		})
	}
}

// With no header, a generated file starts with the line Go tools recognize.
func TestGeneratedFilesStartWithTheMarker(t *testing.T) {
	dir := t.TempDir()
	f := newFile("x")
	f.p("var X = 1")
	if err := f.write(dir, "zz_generated.go"); err != nil {
		t.Fatal(err)
	}
	src, err := os.ReadFile(filepath.Join(dir, "zz_generated.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(src), "// Code generated by diegen. DO NOT EDIT.\n\npackage x\n") {
		t.Errorf("source %q", src)
	}
}

func TestWriteHidden(t *testing.T) {
	// a hidden file, as the dies are, has the build constraint that keeps it
	// from the code generators that build with ignore_autogenerated
	dir := t.TempDir()
	f := newFile("x")
	f.hidden = true
	f.noDeepCopy()
	f.p("type T struct{}")
	if err := f.write(dir, "x.go"); err != nil {
		t.Fatal(err)
	}
	src, err := os.ReadFile(filepath.Join(dir, "x.go"))
	if err != nil {
		t.Fatal(err)
	}
	want := "//go:build !ignore_autogenerated\n\n// Code generated by diegen. DO NOT EDIT.\n\npackage x\n\n// +kubebuilder:object:generate=false\n// +k8s:deepcopy-gen=false\n\ntype T struct{}\n"
	if string(src) != want {
		t.Errorf("got\n%s\nwant\n%s", src, want)
	}
}
