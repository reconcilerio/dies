// marker is the line that starts every generated file after its header, in
// the form Go tools recognize (https://go.dev/s/generatedcode): gopls warns
// before a generated file is edited, and code review tools collapse it.
const marker = "// Code generated by diegen. DO NOT EDIT.\n\n"

// header starts every generated file, above the marker: the contents of the
// -header file, such as a license, or nothing.
var header string

// diePackages is where each name of the die API that generated code uses is.
// The generator writes them as die.Name; writing a file resolves them.
var diePackages = map[string]string{}

func init() {
	for pkg, names := range map[string][]string{
		"base":    {"DieBase", "DieObjectBase", "DieTypedBase", "AsObject", "AsTyped", "DieMutBase", "DieObjectMutBase", "DieTypedMutBase", "AsObjectMut", "AsTypedMut", "Blank", "BlankOf", "DieOf", "DieMutOf"},
		"fields":  {"DieTypedOf", "DieTypedMutOf", "Field", "NewField", "Struct", "NewStruct", "ListMapField", "NewListMap", "MapField", "NewMap", "Value", "ValueOf", "ValueMut", "ValueMutOf", "Optional", "OptionalOf", "OptionalMut", "OptionalMutOf", "Child", "ChildMut", "ListMap", "ListMapOf", "ListMapMut", "ListMapMutOf", "Map", "MapOf", "MapMut", "MapMutOf", "Table"},
		"lists":   {"List", "NewList", "DieListOf"},
		"objects": {"DieObjectOf", "DieObjectMutOf"},
		"codegen": {"Register", "Package", "Annotate", "Object", "CheckManaged", "CheckList", "CheckRegistered", "TypedBlank", "ReleaseApplyConfiguration", "FeedApplyConfiguration", "StampApplyConfiguration", "ReleaseApplyConfigurationE"},
	} {
		for _, n := range names {
			diePackages[n] = "reconciler.io/dies/v2/die/" + pkg
		}
	}
}

var dieName = regexp.MustCompile(`\bdie\.([A-Z][A-Za-z]*)\b`)

// resolveDie rewrites the die API's names to their packages, importing them.
func (f *file) resolveDie(src []byte) ([]byte, error) {
	var err error
	out := dieName.ReplaceAllFunc(src, func(m []byte) []byte {
		name := string(m[len("die."):])
		pkg, ok := diePackages[name]
		if !ok {
			err = fmt.Errorf("diegen: die.%s is not in the die API", name)
			return m
		}
		return []byte(f.use(pkg) + "." + name)
	})
	delete(f.imports, "reconciler.io/dies/v2/die")
	delete(f.aliases, "die")
	return out, err
}

// file accumulates the source and imports of one generated file.
type file struct {
	pkgName string
	imports map[string]string
	aliases map[string]string
	blanks  map[string]bool
	buf     bytes.Buffer
}

func newFile(pkgName string) *file {
	return &file{pkgName: pkgName, imports: map[string]string{}, aliases: map[string]string{}, blanks: map[string]bool{}}
}

// blank imports a package for its initialization only, unless it is also
// imported by name.
func (f *file) blank(importPath string) { f.blanks[importPath] = true }

func (f *file) p(format string, args ...any) {
	fmt.Fprintf(&f.buf, format, args...)
	f.buf.WriteByte('\n')
}

func (f *file) doc(lines []string) {
	for _, l := range lines {
		f.p("// %s", l)
	}
}

// use imports a package and returns its alias. Die packages are aliased
// die<group><version>, other packages by their last element.
func (f *file) use(importPath string) string {
	if a, ok := f.imports[importPath]; ok {
		return a
	}
	alias := path.Base(importPath)
	if rest, ok := strings.CutPrefix(importPath, "reconciler.io/dies/v2/apis/"); ok {
		alias = "die" + strings.ReplaceAll(rest, "/", "")
	} else if importPath == "reconciler.io/dies/v2/die" {
		alias = "die"
	} else if strings.Contains(importPath, "/applyconfigurations/") || strings.Contains(importPath, "/applyconfiguration/") {
		// apply configurations, by group and version, as appsv1ac
		parts := strings.Split(importPath, "/")
		alias = parts[len(parts)-2] + parts[len(parts)-1] + "ac"
	} else if rest, ok := strings.CutPrefix(importPath, "reconciler.io/dies/v2/die/"); ok {
		// the die API's packages, so as not to collide with a die package's
		// own names, such as a variable named fields
		alias = "die" + rest
	} else if parts := strings.Split(importPath, "/"); len(parts) >= 2 && strings.HasPrefix(alias, "v") {
		// versioned packages, such as k8s.io/api/core/v1
		alias = parts[len(parts)-2] + alias
	}
	for base, n := alias, 2; f.aliases[alias] != ""; n++ {
		alias = fmt.Sprintf("%s%d", base, n)
	}
	f.imports[importPath], f.aliases[alias] = alias, importPath
	return alias
}

func (f *file) write(dir, name string) error {
	body, err := f.resolveDie(f.buf.Bytes())
	if err != nil {
		return err
	}
	var src bytes.Buffer
	src.WriteString(header)
	src.WriteString(marker)
	fmt.Fprintf(&src, "package %s\n\n", f.pkgName)
	imports := maps.Clone(f.imports)
	for p := range f.blanks {
		if _, ok := imports[p]; !ok {
			imports[p] = "_"
		}
	}
	if len(imports) > 0 {
		paths := slices.Sorted(maps.Keys(imports))
		src.WriteString("import (\n")
		for _, p := range paths {
			fmt.Fprintf(&src, "\t%s %q\n", imports[p], p)
		}
		src.WriteString(")\n\n")
	}
	src.Write(body)
	out, err := format.Source(src.Bytes())
	if err != nil {
		return fmt.Errorf("formatting %s in %s: %w\n%s", name, dir, err, src.Bytes())
	}
	// formatting a doc comment copied from a type, such as a list whose items
	// are separated by blank lines only some of the time, can change it again,
	// so it is formatted until gofmt leaves it as it is
	for range 3 {
		again, err := format.Source(out)
		if err != nil {
			return fmt.Errorf("formatting %s in %s: %w", name, dir, err)
		}
		if bytes.Equal(again, out) {
			break
		}
		out = again
	}
	file := filepath.Join(dir, name)
	if old, err := os.ReadFile(file); err == nil && bytes.Equal(old, out) {
		progress.wrote(file, false)
		return nil
	}
	if err := os.WriteFile(file, out, 0o644); err != nil {
		return err
	}
	progress.wrote(file, true)
	return nil
}

// removeFile removes a generated file, if it exists.
func removeFile(dir, name string) error {
	file := filepath.Join(dir, name)
	if err := os.Remove(file); err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	progress.deleted(file)
	return nil
}
