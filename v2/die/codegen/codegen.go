// Package codegen is for code generated by diegen: what a die package
// registers, and the checks its generated tests run.
package codegen

import (
	"fmt"
	"reflect"
	"slices"

	"reconciler.io/dies/v2/die/base"
	"reconciler.io/dies/v2/die/internal/core"

	"k8s.io/apimachinery/pkg/runtime"
	"k8s.io/apimachinery/pkg/runtime/schema"
)

// Package is what a die package registers, once, for the types it has dies
// for: how to annotate them, which happens before any of their schemas are
// built, and how to build its field tables, which happens when the fields a
// die manages are asked for. Neither happens at init.
type Package struct {
	// Types are the import paths of the packages declaring the types, such as
	// k8s.io/api/apps/v1 for the dies of its aliases.
	Types    []string
	Annotate func()
	Tables   func()
}

// Register registers a die package. Generated dies call it once per package.
func Register(p Package) bool {
	core.RegisterPackage(p.Types, p.Annotate, p.Tables)
	return true
}

// CheckRegistered reports whether dies registers every kind of a group
// version that upstream does, and no other, each as a die rather than the
// upstream type. Kinds of apimachinery's meta types, such as the options
// metav1.AddToGroupVersion registers, are the same type in both. Generated
// tests call it for every die package of an upstream package that registers
// its types.
func CheckRegistered(dies, upstream func(*runtime.Scheme) error, gv schema.GroupVersion) error {
	ds, us := runtime.NewScheme(), runtime.NewScheme()
	if err := dies(ds); err != nil {
		return err
	}
	if err := upstream(us); err != nil {
		return err
	}
	have, want := ds.KnownTypes(gv), us.KnownTypes(gv)
	var missing, extra, upstreamTypes []string
	for kind, ut := range want {
		dt, ok := have[kind]
		switch {
		case !ok:
			missing = append(missing, kind)
		case ut.PkgPath() == metaPackage:
			if dt != ut {
				extra = append(extra, kind)
			}
		case dt == ut:
			upstreamTypes = append(upstreamTypes, kind)
		}
	}
	for kind := range have {
		if _, ok := want[kind]; !ok {
			extra = append(extra, kind)
		}
	}
	if len(missing)+len(extra)+len(upstreamTypes) == 0 {
		return nil
	}
	slices.Sort(missing)
	slices.Sort(extra)
	slices.Sort(upstreamTypes)
	return fmt.Errorf("the dies of %s don't register as upstream does: kinds without dies %v, kinds upstream doesn't have %v, kinds registered as the upstream type %v", gv, missing, extra, upstreamTypes)
}

const metaPackage = "k8s.io/apimachinery/pkg/apis/meta/v1"

// CheckList reports whether T is still a list, with exactly type and list
// metadata and items, as its list die is. Generated tests call it for every
// list die.
func CheckList[T any]() error {
	have := WireFields[T]()
	slices.Sort(have)
	if want := []string{"apiVersion", "items", "kind", "metadata"}; !slices.Equal(have, want) {
		return fmt.Errorf("the list die for %s does not match its type, which has fields %v rather than %v; regenerate the dies", reflect.TypeFor[T](), have, want)
	}
	return nil
}

// CheckManaged reports whether the die for T manages exactly the fields T
// has now. Generated tests call it for every die.
func CheckManaged[T any]() error {
	var have []string
	for _, f := range base.ManagedFields[T]() {
		have = append(have, f.Wire)
	}
	want := WireFields[T]()
	if slices.Equal(have, want) {
		return nil
	}
	var added, removed []string
	for _, w := range want {
		if !slices.Contains(have, w) {
			added = append(added, w)
		}
	}
	for _, h := range have {
		if !slices.Contains(want, h) {
			removed = append(removed, h)
		}
	}
	return fmt.Errorf("the die for %s does not match its type (new fields %v, removed fields %v); regenerate the dies", reflect.TypeFor[T](), added, removed)
}

// Annotate supplies die tags, keyed by Go field name, for a type whose
// declaration cannot carry them, such as an apimachinery type reused as is.
// It must be called before the type's schema is first used: generated dies
// call it from their package's Annotate, which runs before then.
// Object registers the apiVersion and kind of an object type, for an apply
// patch from a die whose value doesn't have them, such as one a client
// decoded into, which strips them from typed objects. Generated dies call it
// from their package's annotations.
func Object[T any](apiVersion, kind string) {
	core.SetIdentity(reflect.TypeFor[T](), apiVersion, kind)
}

func Annotate[T any](tags map[string]string) {
	core.AnnotateType(reflect.TypeFor[T](), tags)
}

// WireFields returns the wire names of T's fields, with embedded structs
// flattened. Generated tests use it to check that dies match their types.
func WireFields[T any]() []string {
	sd := core.Describe(reflect.TypeFor[T]())
	names := make([]string, len(sd.Fields))
	for i, fd := range sd.Fields {
		names[i] = fd.Wire
	}
	return names
}
